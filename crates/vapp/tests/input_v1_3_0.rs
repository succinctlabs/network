//! Compatibility with the execute input consumed by the released v1.3.0 STF.

mod common;

use alloy::signers::SignerSync;
use alloy_primitives::U256;
use prost::Message;
use spn_network_types::{
    ExecuteProofRequestBody as RpcExecuteBody, ExecutionStatus, MessageFormat, ProofMode,
};
use spn_vapp_core::{
    input::v1_3_0::ExecuteProofRequest, signing::verify_signed_message,
    transactions::VAppTransaction,
};

#[test]
fn binary_execute_preserves_the_released_clear_layout() {
    let test = common::setup();
    let mut tx = common::create_clear_tx(
        &test.requester,
        &test.fulfiller,
        &test.fulfiller,
        &test.auctioneer,
        &test.executor,
        &test.verifier,
        1,
        U256::from(50_000),
        2,
        3,
        4,
        5,
        ProofMode::Groth16,
        ExecutionStatus::Executed,
        true,
    );
    let VAppTransaction::Clear(clear) = &mut tx else { panic!("expected a Clear transaction") };
    let signed_body = clear.execute.body.as_ref().unwrap().encode_to_vec();
    let signature = std::mem::take(&mut clear.execute.signature);
    clear.execute =
        ExecuteProofRequest::from_signed_body(MessageFormat::Binary, signature, &signed_body)
            .unwrap();

    // Generated by serializing this same deterministic transaction at network tag v1.3.0.
    assert_eq!(
        bincode::serialize(&tx).unwrap(),
        include_bytes!("fixtures/clear-v1.3.0.bin").as_slice()
    );
}

const SIGNED_JSON: &[u8] = br#"{"nonce":5,"request_id":[1,2],"execution_status":2,"public_values_hash":[3,4],"cycles":10,"pgus":9,"domain":[5,6],"punishment":null,"failure_cause":null,"variant":3}"#;

#[test]
fn legacy_json_keeps_the_original_signature_verifiable() {
    let executor = common::signer("executor");
    let signature = executor.sign_message_sync(SIGNED_JSON).unwrap().as_bytes().to_vec();
    let request =
        ExecuteProofRequest::from_signed_body(MessageFormat::Json, signature.clone(), SIGNED_JSON)
            .unwrap();
    assert_eq!(request.signature, signature);
    let signer =
        verify_signed_message(request.body.as_ref().unwrap(), &request.signature, request.format())
            .unwrap();
    assert_eq!(signer, executor.address());
}

#[test]
fn rejects_present_binary_trace_including_empty_bytes() {
    for trace in [vec![], vec![7]] {
        let body = RpcExecuteBody { error_trace: Some(trace), ..Default::default() };
        assert!(ExecuteProofRequest::from_signed_body(
            MessageFormat::Binary,
            vec![],
            &body.encode_to_vec(),
        )
        .is_err());
    }
}

#[test]
fn rejects_explicit_json_null_in_an_otherwise_identical_body() {
    let mut body = SIGNED_JSON.strip_suffix(b"}").unwrap().to_vec();
    body.extend_from_slice(br#","error_trace":null}"#);
    assert!(ExecuteProofRequest::from_signed_body(MessageFormat::Json, vec![], &body).is_err());
}
